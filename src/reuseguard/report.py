"""Render a :class:`reuseguard.models.Report` as Markdown or JSON."""

from __future__ import annotations

import html
import json
from datetime import datetime, timezone

from .models import (
    Assessment,
    Decision,
    Finding,
    RepoMeta,
    Report,
    SandboxStatus,
    ScanStatus,
)

_KEY_CHECKS = (
    "Maintained",
    "Code-Review",
    "Dangerous-Workflow",
    "Token-Permissions",
    "Vulnerabilities",
    "Binary-Artifacts",
    "Pinned-Dependencies",
    "Security-Policy",
)

_MAX_FINDINGS_IN_REPORT = 12
_MAX_SUPPRESSED_IN_REPORT = 8


def render(report: Report, fmt: str = "md") -> str:
    if fmt == "json":
        return render_json(report)
    if fmt != "md":
        raise ValueError(f"unsupported report format: {fmt!r}")
    return render_markdown(report)


def render_json(report: Report) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False) + "\n"


def render_markdown(report: Report) -> str:
    counts = report.counts()
    lines: list[str] = ["# ReuseGuard report", ""]

    if report.demo:
        lines.extend(
            [
                "> **Demo report** — generated from built-in fixtures. Repository names, "
                "scores, and findings are fictional.",
                "",
            ]
        )

    header: list[str] = []
    if report.query:
        header.append(f"**Idea:** {_md(report.query, 300)}<br>")
    elif report.seed is not None:
        header.append(f"**Seed:** [{report.seed.full_name}]({_repo_url(report.seed)})<br>")
    header.extend(
        [
            f"**Generated:** {_format_datetime(report.generated_at)}<br>",
            f"**ReuseGuard:** v{report.tool_version}<br>",
            f"**Verdicts:** {counts['use']} USE · {counts['inspect']} INSPECT · "
            f"{counts['avoid']} AVOID",
            "",
        ]
    )

    if report.assessments:
        header.extend(
            [
                "## Summary",
                "",
                "| # | Repository | Role | Stars | Match | Scorecard | Static risk | Sandbox | Verdict |",
                "|---:|---|---|---:|---:|---:|---|---|---|",
            ]
        )
        for index, assessment in enumerate(report.assessments, start=1):
            repo = assessment.candidate.repo
            match = (
                f"{assessment.candidate.similarity.total:.1f}"
                if assessment.candidate.similarity
                else "—"
            )
            scorecard = _score(assessment)
            risk = (
                assessment.scan.risk.value
                if assessment.scan.status is ScanStatus.SCANNED
                else assessment.scan.status.value
            )
            header.append(
                f"| {index} | [{repo.full_name}]({_repo_url(repo)}) | "
                f"{_role(assessment)} | {repo.stars:,} | {match} | {scorecard} | "
                f"{risk} | {_sandbox_cell(assessment)} | **{_decision(assessment)}** |"
            )
    else:
        header.extend(["", "No candidate repositories were found."])

    lines.extend(header)

    lines.extend(
        [
            "",
            "**Verdict key** — **USE**: no medium-or-higher static findings and a passing "
            "reputation gate. **INSPECT FIRST**: something needs human review. "
            "**AVOID**: a high-risk pattern or a failed reputation gate was found.",
            "",
            "> A USE verdict is not a guarantee. Read the evidence and the limitations below.",
        ]
    )

    for index, assessment in enumerate(report.assessments, start=1):
        lines.extend(_render_assessment(index, assessment))

    lines.extend(_render_limitations())
    lines.extend(_render_run_details(report))
    lines.extend(["", f"*Generated by ReuseGuard v{report.tool_version}.*", ""])
    return "\n".join(lines)


def _render_assessment(index: int, assessment: Assessment) -> list[str]:
    repo = assessment.candidate.repo
    verdict = assessment.verdict
    lines: list[str] = ["", f"## {index}. {repo.full_name} — {_decision(assessment)}", ""]

    if repo.description:
        lines.extend([f"> {_md(repo.description, 320)}", ""])

    lines.append(f"- **Repository:** [{repo.full_name}]({_repo_url(repo)})")
    lines.append(f"- **Role:** {_role(assessment)}")
    if assessment.candidate.similarity:
        similarity = assessment.candidate.similarity
        components: list[str] = []
        if similarity.keywords:
            components.append(f"keywords {similarity.keywords:.1f}")
        if similarity.topics:
            components.append(f"topics {similarity.topics:.1f}")
        components.extend(
            [
                f"language {similarity.language:.1f}",
                f"recency {similarity.recency:.1f}",
                f"popularity {similarity.popularity:.1f}",
            ]
        )
        lines.append(f"- **Similarity:** {similarity.total:.1f}/100 ({' · '.join(components)})")
    lines.append(
        f"- **Stats:** {repo.stars:,} stars · {repo.forks:,} forks · "
        f"{_md(repo.language or 'language unknown', 40)} · "
        f"{_md(repo.license_spdx or 'license unknown', 40)}"
    )
    lines.append(
        f"- **Activity:** last push {_format_date(repo.pushed_at) or 'unknown'} · "
        f"created {_format_date(repo.created_at) or 'unknown'}"
    )
    if repo.topics:
        topics = " · ".join(f"`{_code(topic, 40)}`" for topic in repo.topics[:10])
        lines.append(f"- **Topics:** {topics}")
    flags: list[str] = []
    if repo.archived:
        flags.append("archived")
    if repo.fork:
        flags.append("fork")
    if flags:
        lines.append(f"- **Flags:** {', '.join(flags)}")

    lines.extend(["", f"### Reputation filter — {assessment.filter.status.value.upper()}", ""])
    if assessment.filter.score is not None:
        checked = (
            f" (checked {assessment.filter.checked_at})" if assessment.filter.checked_at else ""
        )
        lines.append(f"OpenSSF Scorecard: **{assessment.filter.score:.1f}/10**{checked}")
    else:
        detail = f" — {_md(assessment.filter.error, 200)}" if assessment.filter.error else ""
        lines.append(f"OpenSSF Scorecard: **not available**{detail}")

    for reason in assessment.filter.reasons:
        lines.append(f"- {_md(reason, 300)}")

    if assessment.filter.warnings:
        lines.extend(
            ["", "**Warnings:**", *[f"- {_md(item, 300)}" for item in assessment.filter.warnings]]
        )

    checks = [
        (name, assessment.filter.checks[name])
        for name in _KEY_CHECKS
        if name in assessment.filter.checks
    ]
    if checks:
        lines.extend(["", "| Check | Score |", "|---|---:|"])
        for name, score in checks:
            lines.append(f"| {name} | {score:.0f}/10 |")

    lines.extend(["", f"### Static scan — {_scan_risk(assessment)}", ""])
    scan = assessment.scan
    if scan.status is ScanStatus.SCANNED:
        lines.append(
            f"`{scan.scanner}` scanned {scan.files_scanned:,} files "
            f"({_format_bytes(scan.bytes_scanned)}) with "
            f"{len(scan.effective_findings)} effective finding(s) and "
            f"{len(scan.suppressed_findings)} suppressed."
        )
        if scan.truncated:
            lines.append(
                "**Coverage is incomplete:** the scanner hit a file or size limit, "
                "or reported errors."
            )
        if scan.files_skipped:
            lines.append(
                f"{scan.files_skipped:,} file(s) were skipped (binary, generated, or over the "
                "size limit)."
            )

        effective = sorted(
            scan.effective_findings,
            key=lambda finding: (-finding.severity.rank, finding.path, finding.line or 0),
        )
        if effective:
            lines.extend(["", "| Severity | Rule | Location | Detail |", "|---|---|---|---|"])
            for finding in effective[:_MAX_FINDINGS_IN_REPORT]:
                lines.append(_finding_row(finding))
            if len(effective) > _MAX_FINDINGS_IN_REPORT:
                lines.append(
                    f"\n*{len(effective) - _MAX_FINDINGS_IN_REPORT} more effective finding(s) "
                    "are available in the JSON export.*"
                )
        else:
            lines.append("No matching risk patterns were found.")

        suppressed = scan.suppressed_findings
        if suppressed:
            lines.extend(
                [
                    "",
                    "<details>",
                    f"<summary>{len(suppressed)} finding(s) suppressed as "
                    "documentation/test context</summary>",
                    "",
                    "| Severity | Rule | Location | Reason |",
                    "|---|---|---|---|",
                ]
            )
            for finding in suppressed[:_MAX_SUPPRESSED_IN_REPORT]:
                location = _code(_location(finding), 160)
                lines.append(
                    f"| {finding.severity.value.upper()} | "
                    f"`{_code(finding.rule_id, 160)}` | "
                    f"`{location}` | {_md(finding.suppression_reason or 'suppressed', 80)} |"
                )
            if len(suppressed) > _MAX_SUPPRESSED_IN_REPORT:
                lines.append(
                    f"\n*{len(suppressed) - _MAX_SUPPRESSED_IN_REPORT} more suppressed "
                    "finding(s) are available in the JSON export.*"
                )
            lines.extend(["", "</details>"])
    else:
        lines.append(
            f"Scan status: **{scan.status.value}**"
            + (f" — {_md(scan.error, 240)}" if scan.error else ".")
        )

    lines.extend(_render_sandbox(assessment))

    lines.extend(
        [
            "",
            f"### Verdict — {_decision(assessment)} (confidence: {verdict.confidence.value})",
            "",
        ]
    )
    for reason in verdict.reasons:
        lines.append(f"- {_md(reason, 320)}")

    if verdict.limitations:
        lines.extend(["", "**Caveats:**", *[f"- {_md(item, 320)}" for item in verdict.limitations]])

    return lines


def _render_sandbox(assessment: Assessment) -> list[str]:
    sandbox = assessment.sandbox
    if sandbox is None:
        return []

    if sandbox.status is SandboxStatus.COMPLETED:
        heading = "containment verified" if sandbox.containment_ok else "containment NOT verified"
    else:
        heading = sandbox.status.value

    lines: list[str] = ["", f"### Sandbox — {heading}", ""]

    if sandbox.status is not SandboxStatus.COMPLETED:
        detail = f" — {_md(sandbox.error, 300)}" if sandbox.error else "."
        lines.append(f"Sandbox probe **{sandbox.status.value}**{detail}")
        if sandbox.stderr_tail:
            lines.extend(["", f"`{_code(sandbox.stderr_tail, 400)}`"])
        lines.extend(
            [
                "",
                "> Sandbox verification was requested but produced no containment evidence. "
                "This is not evidence that the repository is safe.",
            ]
        )
        return lines

    config: list[str] = [f"`{_code(sandbox.image or 'unknown image', 120)}`", "one container run"]
    if sandbox.duration_seconds:
        config.append(f"{sandbox.duration_seconds:.1f}s")
    config.extend(
        [
            f"network `{_code(sandbox.network, 20)}`",
            f"`{_code(sandbox.mount_target, 40)}` read-only",
        ]
    )
    if sandbox.memory_mb is not None:
        config.append(f"{sandbox.memory_mb} MB")
    if sandbox.cpus is not None:
        config.append(f"{sandbox.cpus:g} CPU")
    if sandbox.pids_limit is not None:
        config.append(f"{sandbox.pids_limit} PIDs")
    if sandbox.timeout_seconds is not None:
        config.append(f"{sandbox.timeout_seconds:g}s timeout")
    lines.append(" · ".join(config))
    lines.append("")

    probe = sandbox.probe
    files = _probe_int(probe, "files")
    size = _probe_int(probe, "bytes")
    symlinks = _probe_int(probe, "symlinks")
    executables = _probe_int(probe, "executables")
    details: list[str] = []
    if files is None:
        details.append("file count unavailable")
    else:
        text = f"{files:,} file{'s' if files != 1 else ''}"
        if size is not None:
            text += f" ({_format_bytes(size)})"
        details.append(text)
    if symlinks is not None:
        details.append(f"{symlinks:,} symlink{'s' if symlinks != 1 else ''}")
    if executables is not None:
        details.append(f"{executables:,} executable bit{'s' if executables != 1 else ''}")
    details.append(
        f"`{_code(sandbox.mount_target, 40)}` writable: **{_yes_no(probe.get('src_writable'))}**"
    )
    details.append(f"network reachable: **{_yes_no(probe.get('network_reachable'))}**")
    details.append(f"`/tmp` writable: {_yes_no(probe.get('tmp_writable'))}")
    lines.append(" · ".join(details))

    failures: list[str] = []
    if probe.get("src_writable") is True:
        failures.append("the repository mount was writable")
    if probe.get("network_reachable") is True:
        failures.append("the container could reach the network")
    if probe.get("src_entries") is None:
        failures.append("the mount was not readable by the sandbox user")
    if failures:
        lines.extend(
            [
                "",
                "**Containment check failed:** "
                + "; ".join(failures)
                + ". Treat this run as untrusted and do not use it as evidence.",
            ]
        )

    lines.extend(
        [
            "",
            "> The probe only inspects file metadata and checks the mount and network "
            "configuration. It does not execute repository code. A clean result covers one "
            "container run and is not evidence that the repository is safe.",
        ]
    )
    return lines


def _sandbox_cell(assessment: Assessment) -> str:
    sandbox = assessment.sandbox
    if sandbox is None:
        return "—"
    if sandbox.status is SandboxStatus.COMPLETED:
        return "containment ok" if sandbox.containment_ok else "**containment failed**"
    return sandbox.status.value


def _probe_int(probe: dict, key: str) -> int | None:
    value = probe.get(key)
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value


def _yes_no(value: object) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return "unknown"


def _finding_row(finding: Finding) -> str:
    detail = _md(finding.message, 180)
    if finding.evidence:
        detail += f" — `{_code(finding.evidence, 160)}`"
    return (
        f"| {finding.severity.value.upper()} | `{_code(finding.rule_id, 160)}` | "
        f"`{_code(_location(finding), 160)}` | {detail} |"
    )


def _render_limitations() -> list[str]:
    return [
        "",
        "## Limitations",
        "",
        "- ReuseGuard aggregates signals; it does not prove that a repository is safe.",
        "- Static analysis cannot detect every malicious or vulnerable pattern, and it "
        "does not execute any repository code.",
        "- OpenSSF Scorecard measures project practice, not the safety of specific code.",
        "- Recall depends on GitHub Search; missing alternatives are not evidence that none exist.",
        "- Vendored dependencies, generated output, and files over the scanner limits are "
        "not inspected.",
        "- Results reflect public data at the time of the run; a later commit can behave "
        "differently.",
        "- Sandbox verification is opt-in, covers a single container run, and currently checks "
        "container containment only; it does not execute repository code.",
        "- When an external scanner is enabled, its coverage depends on the supplied rule set; "
        "rules that are absent cannot produce findings.",
    ]


def _render_run_details(report: Report) -> list[str]:
    lines = ["", "## Run details", ""]
    lines.append(f"- Elapsed: {report.elapsed_seconds:.1f}s")
    lines.append(f"- Candidates assessed: {len(report.assessments)}")
    if report.settings:
        token_state = "configured" if report.settings.get("token_configured") else "not configured"
        lines.append(
            f"- Limits: {report.settings.get('max_candidates', '?')} candidates, "
            f"{report.settings.get('max_repo_mb', '?')} MB per repository, "
            f"GitHub token {token_state}"
        )
        config_path = report.settings.get("config_path")
        if config_path:
            lines.append(f"- Policy file: `{_code(config_path, 240)}`")
        disabled_rules = report.settings.get("disabled_rules") or []
        if disabled_rules:
            lines.append(f"- Disabled rules: {', '.join(f'`{rule}`' for rule in disabled_rules)}")
        overrides = report.settings.get("severity_overrides") or {}
        if overrides:
            rendered = ", ".join(
                f"`{rule}` → {severity}" for rule, severity in sorted(overrides.items())
            )
            lines.append(f"- Severity overrides: {rendered}")
        suppress_paths = report.settings.get("suppress_paths") or []
        if suppress_paths:
            lines.append(
                "- Extra suppression paths: "
                + ", ".join(f"`{_code(pattern, 120)}`" for pattern in suppress_paths)
            )
        sandbox_mode = report.settings.get("sandbox_mode") or "off"
        if sandbox_mode != "off":
            image = report.settings.get("sandbox_image") or "unknown"
            lines.append(
                f"- Sandbox: mode `{_code(sandbox_mode, 20)}`, image "
                f"`{_code(image, 120)}`, timeout "
                f"{report.settings.get('sandbox_timeout', '?')}s"
            )
        semgrep_config = report.settings.get("semgrep_config")
        if semgrep_config:
            lines.append(
                f"- Scanner: `semgrep`, config `{_code(semgrep_config, 240)}`, "
                f"timeout {report.settings.get('semgrep_timeout', '?')}s"
            )
        if report.settings.get("enable_gitleaks"):
            max_file_kb = int(report.settings.get("max_file_kb") or 1024)
            cap_mb = max(1, -(-max_file_kb // 1024))
            lines.append(
                f"- Secret scan: `gitleaks` (built-in rules), timeout "
                f"{report.settings.get('gitleaks_timeout', '?')}s, "
                f"files above {cap_mb} MB skipped"
            )
        if report.settings.get("enable_osv"):
            lines.append(
                f"- Dependency scan: `osv-scanner` (lockfiles, queries api.osv.dev), "
                f"timeout {report.settings.get('osv_timeout', '?')}s"
            )
    if report.recall_queries:
        lines.append("- Search queries:")
        for query in report.recall_queries:
            lines.append(f"  - `{_code(query, 260)}`")
    else:
        lines.append("- Recall: disabled or no alternatives requested")
    if report.warnings:
        lines.append("- Warnings:")
        for warning in report.warnings:
            lines.append(f"  - {_md(warning, 300)}")
    if report.workdir:
        lines.append(f"- Kept working directory: `{_code(report.workdir, 240)}`")
    return lines


def _role(assessment: Assessment) -> str:
    return assessment.candidate.role or "alternative"


def _repo_url(repo: RepoMeta) -> str:
    """Build links from the validated owner/name pair, not the API's raw URL."""
    try:
        return repo.ref.url
    except ValueError:
        return "https://github.com"


def _decision(assessment: Assessment) -> str:
    return {
        Decision.USE: "USE",
        Decision.INSPECT: "INSPECT FIRST",
        Decision.AVOID: "AVOID",
    }[assessment.verdict.decision]


def _score(assessment: Assessment) -> str:
    score = assessment.filter.score
    return f"{score:.1f}/10" if score is not None else "n/a"


def _scan_risk(assessment: Assessment) -> str:
    scan = assessment.scan
    if scan.status is ScanStatus.SCANNED:
        return "none" if scan.risk.value == "none" else f"{scan.risk.value.upper()} risk"
    return scan.status.value


def _location(finding: Finding) -> str:
    return f"{finding.path}:{finding.line}" if finding.line else finding.path


def _format_datetime(value: datetime) -> str:
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return value.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _format_date(value: datetime | None) -> str | None:
    if value is None:
        return None
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return value.astimezone(timezone.utc).strftime("%Y-%m-%d")


def _format_bytes(value: int) -> str:
    if value >= 1024 * 1024:
        return f"{value / (1024 * 1024):.1f} MB"
    if value >= 1024:
        return f"{value / 1024:.0f} KB"
    return f"{value} B"


def _md(value: object, limit: int = 200) -> str:
    text = " ".join(str(value).split())
    text = html.escape(text, quote=False)
    text = text.replace("|", "\\|")
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def _code(value: object, limit: int = 200) -> str:
    text = " ".join(str(value).split()).replace("`", "'").replace("|", "\\|")
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text
